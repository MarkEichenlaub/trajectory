Borna — Study Plan
Updated May 2026

Competition Targets

8th Balkan Physics Olympiad (BPO8): June 27–30, 2026, Istanbul, Turkey
56th International Physics Olympiad (IPhO): July 4–12, 2026, Bucaramanga, Colombia

Both competitions have theoretical and experimental components. After BPO8, there are approximately five weeks before IPhO. Sessions are focused on high-leverage preparation in Borna's areas of greatest growth potential.

Experimental Skills

Olympiad experiments test measurement technique, uncertainty estimation, linearizing data for log-log or semi-log plots, and writing organized experimental accounts under time pressure. We are treating this as an active skill set — reading instruments precisely, propagating errors correctly, and producing clean and legible write-ups. Checking extreme cases and dimensional analysis before finalizing any result.

Theory: Targeted Refinement

Circuits — especially nonlinear elements. Diodes, transistors in simplified models, I-V characteristic curves, operating-point analysis. These appear regularly at BPhO and IPhO level and require both conceptual clarity and facility with implicit equations.

Optics — wave optics including single-slit and double-slit diffraction, interference, thin-film effects, and resolving power. Geometric optics review as needed.

Electromagnetism — magnetism in matter: permeability, susceptibility, boundary conditions at interfaces, and the basics of ferromagnetism. This is an area where IPhO problems often go beyond standard course coverage.

Special Relativity — four-vectors, Lorentz invariants, relativistic dynamics and collisions, relativistic energy and momentum. Problems at this level require fluency, not just recall of formulas.

Quantum Mechanics — photoelectric effect, de Broglie wavelength, energy quantization, the uncertainty principle, and basic wave functions at the IPhO level.

Statistical Mechanics & Thermodynamics — equipartition, partition functions in simple cases, entropy, heat engines, and Carnot efficiency. Problems often combine thermodynamics with other areas.

Problem Strategy

Our main working material is IPhO past problems, selected by topic, to build recognition of how these subjects appear in competition. Full solutions — including reasoning, not just final answers — are written out carefully. We also review experimental problems from past IPhOs to prepare for that component.

Habits

Writing organized, clearly structured solutions under time pressure.
Checking dimensions and extreme cases before committing to a final answer.
Separating "what is the physics here" from "what is the calculation" at the start of each problem.
